"""业务层与具体虚拟形象平台之间的语义接口。"""
from dataclasses import dataclass, field
from typing import Protocol, runtime_checkable


@dataclass
class AvatarState:
    backend: str
    skin: str = ""
    ready: bool = False
    emotion: str = "default_smile"
    parameters: dict[str, float] = field(default_factory=dict)


@runtime_checkable
class AvatarPort(Protocol):
    capabilities: set[str]

    @property
    def ready(self) -> bool: ...

    async def connect(self) -> bool: ...
    async def close(self) -> None: ...
    async def set_emotion(self, key: str) -> bool: ...
    async def play_action(self, key: str) -> bool: ...
    async def set_head_pose(self, x: float, y: float, z: float,
                            mix: float = 1.0) -> bool: ...
    async def reset_pose(self) -> bool: ...
    async def set_mouth_open(self, value: float) -> bool: ...
    async def get_parameters(self) -> list[dict]: ...
    async def set_parameter(self, name: str, value: float) -> bool: ...
    def state(self) -> AvatarState: ...
